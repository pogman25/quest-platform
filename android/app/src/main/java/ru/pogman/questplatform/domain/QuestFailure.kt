package ru.pogman.questplatform.domain

enum class QuestFailure {
    MATERIAL_EXPORT_FAILED,
    PASSWORD_TOO_SHORT,
    PASSWORD_MISMATCH,
    WRONG_PASSWORD,
    PASSWORD_ALREADY_SET,
    ORGANIZER_REQUIRED,
    GAME_INVALID,
    GAME_NOT_FOUND,
    TEAM_NAME_REQUIRED,
    CODE_INVALID,
    RUN_NOT_FOUND,
    RUN_NOT_STARTED,
    RUN_LAYOUT_CHANGED,
    QUEST_NOT_FOUND,
    NFC_UNAVAILABLE,
    NFC_DISABLED,
    NFC_NO_TEXT,
    NFC_READ_ONLY,
    NFC_TOO_SMALL,
    NFC_IO,
    NFC_WRONG_TAG,
    CAMERA_UNAVAILABLE,
    CAMERA_PERMISSION_REQUIRED,
    PHOTO_INVALID,
    PHOTO_SOURCE_UNAVAILABLE,
    STORAGE_ERROR,
}

class QuestException(val failure: QuestFailure) : IllegalStateException(failure.name)
