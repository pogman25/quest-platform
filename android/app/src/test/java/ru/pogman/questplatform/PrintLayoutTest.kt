class PrintLayoutTest {
    @Test
    fun savedStencilSeedReproducesTheWebVersionThreeKit() {
        val kit = makeStencilKit("МЕТЕЛЬ", 20261116L)
        val numbers =
            kit.glyphs
                .flatMap { glyph ->
                    (listOf(glyph.reference, glyph.base, glyph.complement) + glyph.decoys)
                        .flatMap { strokes ->
                            strokes.flatMap { listOf(it.start.x, it.start.y, it.end.x, it.end.y) }
                        }
                }
                .joinToString(",") { (it * 1_000_000).roundToLong().toString() }
        val hash =
            MessageDigest.getInstance("SHA-256").digest(numbers.toByteArray()).joinToString("") {
                "%02x".format(it)
            }
        // Captured from the original TypeScript generator, not generated by this implementation.
        assertEquals("392d461e538213ebbd18fd071a2772e12835785eecfe8bbad9b1365a6d48ada7", hash)
        assertEquals(kit, makeStencilKit(" метель ", 20261116L))
        assertNotEquals(kit, makeStencilKit("МЕТЕЛЬ", 20261117L))
        val config = WordQuestConfig("", "МЕТЕЛЬ")
        val document = stencilPages(config, kit)
        assertEquals(3, document.pages.size)
        assertEquals(11, document.pages.sumOf { it.marks.filterIsInstance<PrintMark.Rect>().size })
        assertEquals(84.0, stencilPreview(config, kit, 3, false, 0).widthMm, 0.0)
        assertEquals(34.0, stencilPreview(config, kit, 3, false, 0).heightMm, 0.0)
    }

    @Test
    fun duplexPagesAlignAndTheirPrintedQrCanBeDecodedAtEverySize() {
        for (size in listOf(120, 150, 180)) {
            val config = QrQuestConfig("", "demo:room", "offline-duplex-test", size)
            val pages = puzzlePages(config, questQrModules(config.token)).pages
            val picture = pages[0].marks.filterIsInstance<PrintMark.Picture>().single()
            val frame =
                pages[1].marks.filterIsInstance<PrintMark.Rect>().single { it.border != null }
            assertEquals(
                listOf(picture.x, picture.y, picture.width, picture.height),
                listOf(frame.x, frame.y, frame.width, frame.height),
            )
            assertEquals(105.0, picture.x + picture.width / 2, 0.0)
            assertEquals(148.5, picture.y + picture.height / 2, 0.0)
            val width = 840
            val height = 1188
            val pixels = IntArray(width * height) { -1 }
            pages[1]
                .marks
                .filterIsInstance<PrintMark.Rect>()
                .filter { it.fill == INK }
                .forEach { rect ->
                    for (y in
                        floor(rect.y * 4).toInt() until
                            ceil((rect.y + rect.height) * 4).toInt()) for (x in
                        floor(rect.x * 4).toInt() until
                            ceil((rect.x + rect.width) * 4).toInt()) pixels[y * width + x] = INK
                }
            val bitmap = BinaryBitmap(HybridBinarizer(RGBLuminanceSource(width, height, pixels)))
            assertEquals(config.token, MultiFormatReader().decode(bitmap).text)
        }
    }
}
